import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

import config from '../config/env.js';
import { GxCrypto } from '../helpers/galaxyCrypto.helper.js';
import { istDate, istTime } from '../helpers/galaxyKeyDay.helper.js';
import { galaxyLog as logger } from '../helpers/galaxy.helper.js';

// ─────────────────────────────────────────────────────────────────────────────
// Persists the RSA keys involved in the GX daily key-rotation dance. Moved
// unchanged from the working implementation (src/providers/galaxy/gxKeyStore.js).
//
//   GHI (service provider) keys, held by us:
//     ghi-current.pem  (Y) — the last key GHI returned. It encrypts the apiKey on
//                            that day's business calls AND on the next
//                            getCurrentPubKey, also after a missed day; the static
//                            GX_GHI_STATIC_PUBLIC_KEY stands in only before the
//                            first rotation (GHI mail, 29 Oct 2026)
//     ghi-current.json — when Y was received: GHI keys are valid for one IST day
//     ghi-next.pem     (Z) — next day's key, fetched via getNextPubKey
//     ghi-prev.pem     — the key promoteGhi() replaced; kept, never sent with
//
//   key-fetches.json — getCurrentPubKey sends counted today (GHI allows 3 a day)
//
//   NovaCred (consumer) keypairs, generated by us:
//     nc-current.(pem|key)  (A) — GHI encrypts response apiKey with A's public
//     nc-next.(pem|key)     (B/C) — the NEW key we send inside the encrypted
//                                   payload of getCurrent/getNextPubKey
//     nc-prev.(pem|key)     — the current key that the last promotion replaced,
//                             kept because GHI may still encrypt responses with it
//
// All files live under GX_KEY_STORE_DIR (git-ignored: data/galaxy-keys/). PEMs
// are public; the .key files are private and must be protected like any secret.
//
// ONE key store per GHI environment: every getCurrentPubKey registers a new
// NovaCred key with GHI, which breaks business calls made from any other store.
// ─────────────────────────────────────────────────────────────────────────────
export class GxKeyStore {
  constructor(dir = config.galaxy.keyStoreDir) {
    this.dir = dir;
  }

  _ensure() { fs.mkdirSync(this.dir, { recursive: true }); }
  _f(name) { return path.join(this.dir, name); }
  _read(name) { const f = this._f(name); return fs.existsSync(f) ? fs.readFileSync(f, 'utf8') : null; }
  _write(name, data) { this._ensure(); fs.writeFileSync(this._f(name), data, 'utf8'); }
  _readJson(name) { const s = this._read(name); try { return s ? JSON.parse(s) : null; } catch { return null; } }

  // --- GHI public keys ------------------------------------------------------

  /** GHI's current public key (Y). Falls back to the static bootstrap key. */
  ghiCurrent() {
    return this._read('ghi-current.pem') || this.ghiStatic();
  }

  /** When ghi-current was received (ISO string), or null. */
  ghiReceivedAt() { return this._readJson('ghi-current.json')?.receivedAt ?? null; }

  /**
   * True when ghi-current was received on `now`'s IST day at or after `at`
   * (HH:MM IST, from when GHI's key of the day can be fetched). Only then may
   * business calls use it (GHI mail, 29 Oct 2026).
   */
  hasGhiKeyFor(now = new Date(), at = config.galaxy.keyRefreshAt) {
    return Date.parse(this.ghiReceivedAt()) >= istTime(at, now).getTime();
  }

  ghiNext() { return this._read('ghi-next.pem'); }

  /** The static public key shipped in the UAT config (normalized to PEM). */
  ghiStatic() {
    const raw = config.galaxy.ghiStaticPublicKey;
    if (!raw) return null;
    return normalizePem(raw);
  }

  setGhiCurrent(pem, receivedAt = new Date()) {
    this._write('ghi-current.pem', normalizePem(pem));
    this._write('ghi-current.json', `${JSON.stringify({ receivedAt: receivedAt.toISOString(), istDate: istDate(receivedAt) })}\n`);
    logger.info('stored GHI current public key');
  }

  setGhiNext(pem) { this._write('ghi-next.pem', normalizePem(pem)); logger.info('stored GHI next public key'); }

  /** Promote next→current, current→prev (end-of-day rotation). */
  promoteGhi() {
    const cur = this._read('ghi-current.pem');
    const nxt = this._read('ghi-next.pem');
    if (cur) this._write('ghi-prev.pem', cur);
    if (nxt) { this._write('ghi-current.pem', nxt); return true; }
    return false;
  }

  // --- NovaCred keypairs ----------------------------------------------------

  /** Current consumer keypair (A). Generated on first use. */
  ncCurrent() {
    let pub = this._read('nc-current.pem');
    let priv = this._read('nc-current.key');
    if (!pub || !priv) {
      ({ publicKey: pub, privateKey: priv } = GxCrypto.generateRsaKeyPair());
      this._write('nc-current.pem', pub);
      this._write('nc-current.key', priv);
      logger.info('generated NovaCred current keypair (A)');
    }
    return { publicKey: pub, privateKey: priv };
  }

  /** The consumer keypair that the last promotion replaced, or null. */
  ncPrev() {
    const pub = this._read('nc-prev.pem');
    const priv = this._read('nc-prev.key');
    return pub && priv ? { publicKey: pub, privateKey: priv } : null;
  }

  /** Fresh consumer keypair (B/C) to send in a key-fetch payload. */
  ncGenerateNext() {
    const { publicKey, privateKey } = GxCrypto.generateRsaKeyPair();
    this._write('nc-next.pem', publicKey);
    this._write('nc-next.key', privateKey);
    return { publicKey, privateKey };
  }

  /**
   * After a successful key fetch, the "next" consumer key becomes current and
   * the replaced current key is kept as nc-prev.
   */
  promoteNc() {
    const pub = this._read('nc-next.pem');
    const priv = this._read('nc-next.key');
    if (pub && priv) {
      const curPub = this._read('nc-current.pem');
      const curPriv = this._read('nc-current.key');
      if (curPub && curPriv && curPub !== pub) {
        this._write('nc-prev.pem', curPub);
        this._write('nc-prev.key', curPriv);
      }
      this._write('nc-current.pem', pub);
      this._write('nc-current.key', priv);
      return true;
    }
    return false;
  }

  // --- getCurrentPubKey quota -----------------------------------------------

  /** getCurrentPubKey sends counted on `now`'s IST day. */
  keyFetchesOn(now = new Date()) {
    const c = this._readJson('key-fetches.json');
    return c && c.istDate === istDate(now) ? c.count : 0;
  }

  /** Count one getCurrentPubKey send. Called before sending, so a failed or interrupted send counts too. */
  countKeyFetch(now = new Date()) {
    this._write('key-fetches.json', `${JSON.stringify({ istDate: istDate(now), count: this.keyFetchesOn(now) + 1 })}\n`);
  }
}

export function normalizePem(pem) {
  const s = String(pem).trim();
  if (s.includes('BEGIN')) return s;
  const wrapped = s.replace(/\s+/g, '').match(/.{1,64}/g).join('\n');
  return `-----BEGIN PUBLIC KEY-----\n${wrapped}\n-----END PUBLIC KEY-----\n`;
}

/**
 * Inverse of normalizePem: the bare base64 SPKI body on one line, with no
 * BEGIN/END lines and no line breaks. This is the form GHI wants as the
 * plaintext of a getCurrent/getNextPubKey payload (GHI mail, 30 Sep 2026).
 */
export function pemBody(pem) {
  return crypto.createPublicKey(normalizePem(pem)).export({ type: 'spki', format: 'der' }).toString('base64');
}
